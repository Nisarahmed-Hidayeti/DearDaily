  legacyPageIcons.some((v) => v === value) ? value : null
export function entryIcon(
  document: { icon?: string } | null | undefined,
  legacy?: string | null,
) {
  return isPageEmoji(document?.icon) ? document.icon : (legacy ?? null)
}
