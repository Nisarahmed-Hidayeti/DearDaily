export const emojiCatalog = Object.entries(groups)
  .flatMap(([category, rows]) =>
    rows.map((row) => {
      const space = row.indexOf(' ')
      return {
        emoji: row.slice(0, space),
        keywords: row.slice(space + 1),
        category,
      }
    }),
  )
  .filter((item, i, all) => all.findIndex((v) => v.emoji === item.emoji) === i)
export const emojiCategories = Object.keys(groups)
const allowed = new Set(emojiCatalog.map((v) => v.emoji))
export const isPageEmoji = (value: unknown): value is string =>
  typeof value === 'string' && allowed.has(value)
